"""Writes plugin/sammi.sister/sister_art.h: SISTER's still art (sister.svg, Hundekraft's, unchanged) as a C string,
so the plugin stays one .opmod (opus_art_text writes it to /yaffs2/mod/sammi.sister/sister.svg at start).

    python3 tools/gen_art.py
"""
from pathlib import Path

P = Path(__file__).resolve().parents[1] / 'plugin' / 'sammi.sister'
svg = (P / 'sister.svg').read_bytes()
assert len(svg) <= 64 * 1024, 'opus_art_text takes 64 KB at most'
text = svg.decode('ascii')
lines = ['/* Generated by tools/gen_art.py from sister.svg (SISTER\'s still art by Hundekraft, unchanged).',
         ' * GPL-3.0-or-later with the OP-1 firmware permission (NOTICE). Do not edit. */',
         '#ifndef SISTER_ART_H', '#define SISTER_ART_H',
         f'#define SISTER_SVG_LEN {len(svg)}u',
         'static const char sister_svg[] =']
for row in text.splitlines(keepends=True):
    lines.append('    "' + row.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"')
lines[-1] += ';'
lines += ['#endif', '']
(P / 'sister_art.h').write_text('\n'.join(lines), newline='\n')
print(f'sister_art.h: {len(svg)} bytes of SVG')
